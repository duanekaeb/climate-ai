def test_fit_room_offsets_day_night(db):
    end = datetime(2026, 7, 10, 5, 0, tzinfo=UTC)
    start = end - timedelta(days=2)
    want = {"school_room": (1.5, 0.5), "kitchen": (-0.8, -0.3), "office": (2.0, 2.0), "hallway": (0.2, 0.2),
            "toy_room": (0.4, 0.1)}
    sensors = {"school_room": ["main.school_room"], "kitchen": ["main.kitchen"], "office": ["bed.office"],
               "hallway": ["main.hallway_tstat"], "toy_room": ["up.toy_room", "up.toy_room_tstat"]}
    unit_of = {"school_room": "main", "kitchen": "main", "office": "bed", "hallway": "main", "toy_room": "up"}
    zone = {"main": 76.0, "up": 77.0, "bed": 75.0}
    rt, rd = [], []
    t = start
    while t < end:
        local_h = (t.hour - 5) % 24
        night = local_h >= 21 or local_h < 7
        for u, z in zone.items():
            rt.append(dict(ts=t, unit_key=u, comp_cool1=120, zone_temp_f=z, cool_sp_f=z, heat_sp_f=68.0,
                           hvac_mode="cool", source="test"))
        for room, (day_off, night_off) in want.items():
            for skey in sensors[room]:
                rd.append(dict(ts=t, sensor_key=skey, temp_f=zone[unit_of[room]] + (night_off if night else day_off),
                               source="test"))
        t += timedelta(minutes=5)
    _insert(db, Runtime5m, rt)
    _insert(db, Reading5m, rd)
    first = rc.fit_room_offsets(db, end, days=2)
    fit_id = rc.fit_room_offsets(db, end, days=2)
    assert db.get(ModelFit, first).status == "retired"
    fit = db.get(ModelFit, fit_id)
    assert fit.kind == "room_offsets" and fit.status == "active"
    off = fit.params["offsets"]
    for room, (day_off, night_off) in want.items():
        assert off[room]["day"] == pytest.approx(day_off, abs=0.01)
        assert off[room]["night"] == pytest.approx(night_off, abs=0.01)
        assert fit.params["n"][room]["day"] > 0 and fit.params["n"][room]["night"] > 0
        assert fit.params["by_mode"][room]["cool"]["day"] == pytest.approx(day_off, abs=0.01)
    assert "twins_room" not in off and "foyer" not in off and "living_room" not in off  # no data / no sensor
    assert rc.fit_room_offsets(db, end - timedelta(days=30), days=2) is None


