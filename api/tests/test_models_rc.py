def _insert(db, table, rows):
    for i in range(0, len(rows), 5000):
        db.execute(insert(table).values(rows[i : i + 5000]).on_conflict_do_nothing())
    db.flush()


def write_rc_history(db, model: rc.RCModel, end: datetime, days: int, seed: int = 3, sun_on: bool = True,
                     noise: float = 0.02) -> dict:
    """Synthetic history generated by the RC equations themselves (15-minute Euler steps, the
    ideal thermostat holding random setpoints), written the way ecobee reports it: three
    identical 5-minute runtime rows per 15-minute slot plus hourly Open-Meteo weather."""
    rng = np.random.default_rng(seed)
    start = end - timedelta(days=days)
    n = days * 96
    cloud_by_day = rng.uniform(0.2, 1.0, days + 2)
    weather = []
    t = start - timedelta(hours=3)
    while t <= end + timedelta(hours=3):
        local_h = (t.hour - 5) % 24 - 0.5  # preceding-hour mean centred half an hour earlier
        d = min(days + 1, max(0, (t - start).days))
        sw = max(0.0, np.sin((local_h - 6) / 12 * np.pi)) * 900.0 * cloud_by_day[d] if sun_on else 0.0
        weather.append(dict(ts=t, source="open-meteo", kind="observed", temp_f=80.0, rh=50.0, dewpoint_f=60.0,
                            cloud_cover=30.0, shortwave_wm2=float(sw), wind_mph=4.0, precip_in=0.0))
        t += timedelta(hours=1)
    _insert(db, WeatherHour, weather)
    _, sun, _, _ = rc.weather_inputs(db, start, n)  # exactly what the loader will see
    hours = np.arange(n) / 4.0
    local_h = (hours + start.hour - 5) % 24
    t_out = 80 + 9 * np.sin((local_h - 10) / 24 * 2 * np.pi) + 4 * np.sin(hours / 24 / 5.0) + rng.normal(0, 0.3, n)
    sp = np.empty((n, 3))
    for z in range(3):
        i = 0
        while i < n:
            span = int(rng.integers(8, 24))
            sp[i : i + span, z] = rng.choice([72, 74, 76, 78, 80, 86])
            i += span
    T, on = rc.emulate(model, np.array([[76.0, 77.0, 75.0]]), t_out[:, None], sun[:, None], sp[:, None, :])
    T = T[:-1, 0, :] + rng.normal(0, noise, (n, 3))
    on = on[:, 0, :]
    rows = []
    for k in range(n):
        for j in range(3):
            ts = start + timedelta(minutes=15 * k + 5 * j)
            for z, u in enumerate(rc.ZONES):
                secs = int(round(on[k, z] * 300))
                rows.append(dict(ts=ts, unit_key=u, comp_cool1=secs, comp_cool2=0, fan=secs, hvac_mode="cool",
                                 zone_temp_f=float(T[k, z]), cool_sp_f=float(sp[k, z]), heat_sp_f=68.0,
                                 outdoor_temp_f=float(t_out[k]), source="test"))
    _insert(db, Runtime5m, rows)
    return {"start": start, "n": n}


def _rel_err(fit_params: dict, truth: rc.RCModel) -> dict[str, float]:
    out = {}
    for z in rc.ZONES:
        for name, true in zip(rc.PARAM_NAMES[z], getattr(truth, z), strict=True):
            out[f"{z}.{name}"] = abs(fit_params["zones"][z][name] / true - 1)
    return out


END = datetime(2026, 7, 29, 5, 0, tzinfo=UTC)  # local midnight (CDT)


def test_fit_rc_recovers_known_parameters_and_beats_persistence(db):
    write_rc_history(db, TRUE, END, days=28)
    t0 = time.monotonic()
    ids = rc.fit_rc(db, END, days=28)
    assert time.monotonic() - t0 < 30
    assert len(ids) == 1  # only cooling has data
    fit = db.get(ModelFit, ids[0])
    assert fit.kind == "rc" and fit.mode == "cool" and fit.unit_key is None
    errs = _rel_err(fit.params, TRUE)
    assert max(errs.values()) < 0.25, errs
    m = fit.metrics
    assert m["rmse_1h"] < m["persistence_rmse_1h"] and m["rmse_1h"] <= 1.0
    assert m["rmse_24h"] is not None and m["n_points"] > 1500 and m["runtime_days"] >= 5
    assert m["runtime_err_rmse"] < 0.05
    assert fit.status == "active"
    assert fit.params["unidentified"] == []
    assert fit.params["physical"]["C"]["up"] == pytest.approx(0.10 / 0.14, rel=0.25)
    assert fit.train_end < local_date(END - timedelta(days=6), TZ)
    assert "pinned down" in fit.notes

    # a refit retires the previous active fit of the same mode
    ids2 = rc.fit_rc(db, END, days=28)
    assert db.get(ModelFit, ids[0]).status == "retired" and db.get(ModelFit, ids2[0]).status == "active"
    assert set(rc.active_rc(db)) == {"cool"}


def test_fit_rc_flags_parameters_without_excitation(db):
    write_rc_history(db, TRUE, END, days=21, sun_on=False, seed=5)
    ids = rc.fit_rc(db, END, days=21)
    fit = db.get(ModelFit, ids[0])
    assert {"main.sun", "up.sun", "bed.sun"} <= set(fit.params["unidentified"])
    assert "up.sun" in fit.notes and "Not pinned down" in fit.notes
    # everything that WAS excited is still recovered
    errs = _rel_err(fit.params, TRUE)
    assert max(v for k, v in errs.items() if not k.endswith(".sun")) < 0.25


