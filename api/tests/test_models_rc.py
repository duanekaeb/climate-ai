def _baselines():
    return {(u, "cool"): SimpleNamespace(unit_key=u, mode="cool", balance_point_f=65.0, slope_s_per_dd=1800.0,
                                         intercept_s=600.0, cvrmse=0.12, resid_std_s=2400.0, resid_lag1=0.2)
            for u in ("main", "up", "bed")}


def _insert_active_rc(db, err=0.05):
    params = {"mode": "cool", "form": "rate", "dt_h": 0.25, "zones": TRUE.to_params()}
    db.add(ModelFit(kind="rc", mode="cool", params=params, status="active",
                    metrics={"rmse_1h": 0.3, "runtime_err_rmse": err, "runtime_err_scatter": err}))
    db.flush()


def test_backtest_rule_of_thumb_sign(db, monkeypatch):
    make_history(db, days=10)
    monkeypatch.setattr("climate.analytics.baseline.active_fits", lambda s: _baselines())
    same = bt.backtest(db, {}, days=7)
    assert same.model == "rule_of_thumb" and same.delta_pct == pytest.approx(0.0)
    assert same.beats_model_uncertainty is False
    cooler = bt.backtest(db, {"linked_offset_f": 3.0}, days=7)  # main floor 2°F cooler on empty afternoons
    assert cooler.model == "rule_of_thumb"
    assert cooler.candidate_runtime_min > cooler.current_runtime_min and cooler.delta_pct > 0
    assert cooler.comfort_violation_min_candidate is None and "floor coupling" in cooler.note
    warmer = bt.backtest(db, {"linked_floors_enabled": False}, days=7)  # main floats to away instead
    assert warmer.delta_pct < 0
    with pytest.raises(ValueError):
        bt.backtest(db, {"not_a_param": 1}, days=7)


def test_backtest_without_model_or_baselines(db, monkeypatch):
    make_history(db, days=3)
    monkeypatch.setattr("climate.analytics.baseline.active_fits", lambda s: {})
    out = bt.backtest(db, {"linked_offset_f": 2.0}, days=7)
    assert out.model == "rule_of_thumb" and out.delta_pct is None and not out.beats_model_uncertainty


def test_backtest_rc_path_sign_and_interval(db, monkeypatch):
    make_history(db, days=10)
    _insert_active_rc(db)
    monkeypatch.setattr("climate.analytics.baseline.active_fits", lambda s: {})
    same = bt.backtest(db, {}, days=7)
    assert same.model == "rc" and same.delta_pct == pytest.approx(0.0, abs=1e-9)
    assert same.beats_model_uncertainty is False
    out = bt.backtest(db, {"linked_offset_f": 3.0}, days=7)
    assert out.model == "rc" and out.days >= 6
    assert out.candidate_runtime_min > out.current_runtime_min and out.delta_pct > 0
    lo, hi = out.ci90_pct
    assert lo < out.delta_pct < hi
    assert out.comfort_violation_min_current is not None and out.comfort_violation_min_candidate is not None
    assert "Weather data by Open-Meteo.com" in out.note
    # a much less accurate model cannot claim the same difference
    db.execute(ModelFit.__table__.update().values(metrics={"runtime_err_rmse": 0.9, "runtime_err_scatter": 0.9}))
    vague = bt.backtest(db, {"linked_offset_f": 3.0}, days=7)
    assert vague.delta_pct == pytest.approx(out.delta_pct)
    assert vague.ci90_pct[1] - vague.ci90_pct[0] > hi - lo and not vague.beats_model_uncertainty


def test_simulate_rc_past_and_future_days(db, monkeypatch):
    make_history(db, days=10)
    _insert_active_rc(db)
    monkeypatch.setattr("climate.analytics.baseline.active_fits", lambda s: {})
    today = local_date(utcnow(), TZ)
    past = bt.simulate(db, {}, today - timedelta(days=2))
    assert past.model == "rc" and set(past.units) == {"main", "up", "bed"}
    start, end = day_bounds_utc(today - timedelta(days=2), TZ)
    n = int((end - start).total_seconds() // 900)
    assert all(len(p) == n for p in past.units.values())
    assert past.units["main"][0].ts == start and past.total_runtime_min > 0
    assert all(0 <= p.runtime_s <= 900 for pts in past.units.values() for p in pts)
    cooler = bt.simulate(db, {"linked_offset_f": 3.0}, today - timedelta(days=2))
    if (today - timedelta(days=2)).weekday() < 5:
        assert cooler.total_runtime_min > past.total_runtime_min
    future = bt.simulate(db, {})  # tomorrow: no forecast stored -> last week's weather
    assert future.model == "rc" and "last week" in future.note and future.total_runtime_min > 0


def test_simulate_rule_of_thumb(db, monkeypatch):
    make_history(db, days=10)
    monkeypatch.setattr("climate.analytics.baseline.active_fits", lambda s: _baselines())
    today = local_date(utcnow(), TZ)
    out = bt.simulate(db, {}, today - timedelta(days=1))
    assert out.model == "rule_of_thumb" and set(out.units) == {"main", "up", "bed"}
    assert out.total_runtime_min > 0 and "setpoints" in out.note
    assert {p.temp_f for p in out.units["up"]} <= {74.0, 77.0, 82.0}
